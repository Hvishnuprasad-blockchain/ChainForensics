from __future__ import annotations

import json
from pathlib import Path


def load_forensic_ledger_abi() -> list[dict]:
    """
    Load the ABI generated by Hardhat.

    The ABI is read from the compiled Solidity artifact so the
    Python client always uses the ABI produced by the current
    ForensicLedger.sol contract.
    """

    project_root = Path(__file__).resolve().parents[2]

    artifact_path = (
        project_root
        / "artifacts"
        / "contracts"
        / "ForensicLedger.sol"
        / "ForensicLedger.json"
    )

    if not artifact_path.exists():
        raise FileNotFoundError(
            f"Hardhat contract artifact not found: {artifact_path}"
        )

    with artifact_path.open("r", encoding="utf-8") as file:
        artifact = json.load(file)

    abi = artifact.get("abi")

    if not isinstance(abi, list):
        raise ValueError("ForensicLedger artifact does not contain a valid ABI.")

    return abi